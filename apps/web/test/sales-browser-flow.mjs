// Browser-only sales acceptance helper. Every business transition goes through the UI.
import assert from 'node:assert/strict';
import { randomInt } from 'node:crypto';
export async function createSalesOrderFromBrowser({ browser, adminPage, staff, password, prisma, origin, contexts, errors }) {
  const start = Date.now();
  const name = `Public Browser ${randomInt(1e8)}`;
  const newPage = async () => {
    const context = await browser.newContext({ baseURL: origin, viewport: { width: 360, height: 800 } }); contexts.push(context);
    const page = await context.newPage(); page.on('pageerror', error => errors.push(error.message)); return page;
  };
  const publicPage = await newPage();
  await publicPage.goto('/enquire');
  await publicPage.getByRole('button', { name: 'Submit enquiry' }).click();
  await publicPage.getByRole('alert').filter({ hasText: 'Check the highlighted fields' }).waitFor();
  for (const [label, value] of [['Name', name], ['Mobile number', `7${String(randomInt(1e9)).padStart(9, '0')}`], ['Address', '44 Browser Solar Road'], ['City', 'Nagpur'], ['Pincode', '440001']]) await publicPage.getByRole('textbox', { name: label, exact: true }).fill(value);
  await publicPage.getByLabel('Requested capacity (kW)', { exact: true }).selectOption('3');
  await publicPage.getByLabel('System type (optional)', { exact: true }).selectOption('ON_GRID');
  const received = publicPage.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/v1/enquiries');
  await publicPage.getByRole('button', { name: 'Submit enquiry' }).click();
  const response = await received; assert.equal(response.status(), 201);
  const enquiryId = (await response.json()).data.id;
  await publicPage.getByText('Your enquiry has been received. Thank you.', { exact: true }).waitFor();
  const persisted = await prisma.enquiry.findUniqueOrThrow({ where: { id: enquiryId } });
  const customer = await prisma.customer.findUniqueOrThrow({ where: { id: persisted.customerId } });
  assert.equal(customer.name, name);
  const sales = await newPage();
  await sales.goto(`/workspace/sales/enquiries/${enquiryId}`);
  await sales.getByRole('textbox', { name: 'Email', exact: true }).fill(staff.SALES.email);
  await sales.getByLabel('Password', { exact: true }).fill(password);
  await sales.getByRole('button', { name: 'Sign in', exact: true }).click();
  await sales.getByRole('heading', { name, exact: true }).waitFor();
  await sales.getByRole('button', { name: 'Mark contacted', exact: true }).click();
  await sales.locator('.status-line').filter({ hasText: 'Contacted' }).waitFor();
  await sales.getByRole('button', { name: 'Qualify', exact: true }).click();
  let dialog = sales.getByRole('dialog', { name: 'Qualification call' });
  await dialog.getByRole('textbox', { name: 'Shadow-free roof area (m²)', exact: true }).fill('80.00');
  await dialog.getByRole('textbox', { name: 'Monthly electricity bill (₹)', exact: true }).fill('2500.00');
  await dialog.getByLabel('Grid connection suitable', { exact: true }).selectOption('yes');
  await dialog.getByLabel('Outcome', { exact: true }).selectOption('QUALIFIED');
  await dialog.getByRole('button', { name: 'Save outcome' }).click();
  await sales.getByRole('button', { name: 'Schedule survey', exact: true }).click();
  dialog = sales.getByRole('dialog', { name: 'Schedule a site survey' });
  await dialog.getByLabel('Technician', { exact: true }).selectOption(staff.TECHNICIAN.id);
  await dialog.getByLabel('Date and time', { exact: true }).fill(new Date(Date.now() + 86400000).toISOString().slice(0, 16));
  await dialog.getByRole('button', { name: 'Schedule', exact: true }).click();
  await sales.getByRole('heading', { name: 'Revision 1: Scheduled', exact: true }).waitFor();
  assert.equal(await sales.getByRole('button', { name: 'Create quote', exact: true }).count(), 0, 'unapproved survey cannot quote');
  const tech = await newPage();
  await tech.goto('/workspace/sales');
  await tech.getByRole('textbox', { name: 'Email', exact: true }).fill(staff.TECHNICIAN.email);
  await tech.getByLabel('Password', { exact: true }).fill(password);
  await tech.getByRole('button', { name: 'Sign in', exact: true }).click();
  await tech.getByRole('heading', { name: 'My site surveys', exact: true }).waitFor();
  await tech.getByRole('button', { name: 'Record measurements', exact: true }).click();
  dialog = tech.getByRole('dialog', { name: 'Site measurements' });
  await dialog.getByLabel('Roof direction', { exact: true }).selectOption('S');
  for (const [label, value] of [['Roof tilt (degrees)', '18.5'], ['Cable distance (m)', '22.00'], ['Usable roof area (m²)', '80.00']]) await dialog.getByRole('textbox', { name: label, exact: true }).fill(value);
  const submitted = tech.waitForResponse(response => response.request().method() === 'POST' && /\/surveys\/[^/]+\/submit$/.test(new URL(response.url()).pathname));
  await dialog.getByRole('button', { name: 'Submit survey', exact: true }).click(); assert.equal((await submitted).status(), 200);
  await sales.reload();
  await sales.getByRole('button', { name: 'Approve survey', exact: true }).click();
  await sales.getByRole('button', { name: 'Create quote', exact: true }).click();
  dialog = sales.getByRole('dialog', { name: 'Create quote' });
  await dialog.getByLabel('Package', { exact: true }).selectOption('c0010000-0000-4000-8000-000000001003');
  await dialog.getByRole('button', { name: 'Save quote', exact: true }).click();
  await sales.getByRole('heading', { name: 'Quote revision 1: Draft', exact: true }).waitFor();
  await sales.reload(); await sales.getByRole('heading', { name: 'Quote revision 1: Draft', exact: true }).waitFor();
  await sales.getByRole('button', { name: 'Record quote sent', exact: true }).click();
  dialog = sales.getByRole('dialog', { name: 'Record manual sending' });
  await dialog.getByLabel('Sent by', { exact: true }).selectOption('PRINT');
  await dialog.getByRole('button', { name: 'Record sent', exact: true }).click();
  await sales.getByRole('button', { name: 'Record acceptance', exact: true }).click();
  dialog = sales.getByRole('dialog', { name: 'Customer acceptance' });
  await dialog.getByRole('textbox', { name: 'Accepted by', exact: true }).fill(name);
  await dialog.getByLabel('Acceptance channel', { exact: true }).selectOption('IN_PERSON');
  await dialog.getByRole('button', { name: 'Record acceptance', exact: true }).click();
  const confirmed = sales.waitForResponse(response => response.request().method() === 'POST' && new URL(response.url()).pathname === '/api/v1/orders');
  await sales.getByRole('button', { name: 'Confirm order', exact: true }).click();
  const orderResponse = await confirmed; assert.equal(orderResponse.status(), 201); const order = (await orderResponse.json()).data;
  await sales.reload(); await sales.getByRole('link', { name: order.displayNumber, exact: true }).waitFor();
  await adminPage.goto(`/workspace/orders/${order.id}`);
  await adminPage.getByRole('textbox', { name: 'Amount received (₹)', exact: true }).fill(order.invoice.total);
  await adminPage.getByLabel('Method', { exact: true }).selectOption('UPI');
  await adminPage.getByRole('textbox', { name: 'Receipt or bank reference', exact: true }).fill(`UI-${enquiryId}`);
  await adminPage.getByRole('button', { name: 'Record receipt', exact: true }).click();
  await adminPage.getByText('This invoice is fully paid.', { exact: true }).waitFor();
  await adminPage.reload(); await adminPage.getByText('This invoice is fully paid.', { exact: true }).waitFor();
  assert.equal((await prisma.invoice.findUniqueOrThrow({ where: { id: order.invoice.id } })).status, 'PAID');
  assert.equal(await adminPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  console.log('PASS public/sales/technician/quote/order/payment UI', JSON.stringify({ enquiryId, orderId: order.id, seconds: ((Date.now() - start) / 1000).toFixed(1) }));
  return { order, customer };
}
